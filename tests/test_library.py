class TestStore(StoreBase):
    def test_atomic_write_private_modes_and_no_leftovers(self):
        e = self.lib.add_bytes("Phone Stand v3.3mf", make_3mf(), folder="Stands")
        path = os.path.join(self.root, "files", "Phone Stand v3.3mf")
        self.assertTrue(os.path.isfile(path))
        self.assertEqual(stat.S_IMODE(os.stat(path).st_mode), 0o600)
        self.assertEqual(stat.S_IMODE(os.stat(os.path.join(self.root, "index.json")).st_mode), 0o600)
        self.assertEqual(stat.S_IMODE(os.stat(os.path.join(self.root, "files")).st_mode), 0o700)
        self.assertEqual(stat.S_IMODE(os.stat(os.path.join(self.root, "thumbs", e["thumb"])).st_mode), 0o600)
        self.assertEqual(os.listdir(os.path.join(self.root, ".incoming")), [])        # the temp file moved, none left
        self.assertFalse([n for n in os.listdir(self.root) if n.endswith(".tmp")])
        self.assertEqual(rd(path), make_3mf())
        self.assertEqual(e["sha256"], __import__("hashlib").sha256(make_3mf()).hexdigest())

    def test_an_unfinished_upload_is_never_listed_and_is_swept(self):
        inc = self.lib.begin_incoming()
        inc.write(b"half a file")
        self.assertEqual(self.lib.entries(), [])
        self.assertEqual(os.listdir(os.path.join(self.root, "files")), [])
        self.assertTrue(os.listdir(os.path.join(self.root, ".incoming")))
        self.assertEqual(stat.S_IMODE(os.stat(inc.path).st_mode), 0o600)
        self.lib.sweep_incoming()
        self.assertEqual(os.listdir(os.path.join(self.root, ".incoming")), [])

    def test_a_failed_parse_does_not_lose_or_half_write_the_file(self):
        e = self.lib.add_bytes("junk.3mf", b"this is not a zip")
        self.assertEqual(e["meta"].get("error") is not None, True)
        self.assertTrue(os.path.isfile(self.lib.file_path("junk.3mf")))

    def test_size_cap_stops_the_stream_and_removes_the_temp_file(self):
        lib = library.Library(self.root, max_bytes=1024)
        inc = lib.begin_incoming()
        inc.write(b"x" * 1000)
        with self.assertRaises(library.TooLarge):
            inc.write(b"x" * 100)
        self.assertEqual(os.listdir(os.path.join(self.root, ".incoming")), [])
        with self.assertRaises(library.TooLarge):
            lib.check_can_add("a.3mf", size=2048)
        with self.assertRaises(library.TooLarge):
            lib.add_bytes("big.3mf", b"y" * 5000)
        self.assertEqual(lib.entries(), [])

    def test_the_cap_comes_from_a_setting_with_a_500mb_default(self):
        self.assertEqual(library.max_file_bytes(), 500 * 1048576)
        with mock.patch.dict(os.environ, {"FABRICA_LIBRARY_MAX_MB": "7"}):
            self.assertEqual(library.max_file_bytes(), 7 * 1048576)
            self.assertEqual(library.Library(self.root).max_bytes, 7 * 1048576)
        with mock.patch.dict(os.environ, {"FABRICA_LIBRARY_MAX_MB": "junk"}):
            self.assertEqual(library.max_file_bytes(), 500 * 1048576)

    def test_empty_file_and_duplicates_and_replace(self):
        with self.assertRaises(library.InvalidName):
            self.lib.add_bytes("empty.3mf", b"")
        self.lib.add_bytes("Phone Stand v3.3mf", make_3mf(), folder="Stands")
        with self.assertRaises(library.Exists):
            self.lib.add_bytes("Phone Stand v3.3mf", make_3mf())
        with self.assertRaises(library.Exists):
            self.lib.add_bytes("PHONE STAND V3.3MF", make_3mf())            # case-insensitive (macOS-style volumes)
        e = self.lib.add_bytes("Phone Stand v3.3mf", make_3mf(grams=99.0), replace=True)
        self.assertEqual(e["folder"], "Stands")                              # replacing keeps the folder
        self.assertEqual(e["meta"]["weight_g"], 99.0)
        self.assertEqual(len(self.lib.entries()), 1)

    def test_path_traversal_cannot_reach_outside_the_files_folder(self):
        for n in ("../x.3mf", "a/../../x.3mf", "..%2Fx.3mf", "/etc/hosts.3mf"):
            with self.assertRaises(library.LibraryError):
                self.lib.add_bytes(n, make_3mf())
            with self.assertRaises(library.LibraryError):
                self.lib.file_path(n)
            with self.assertRaises(library.LibraryError):
                self.lib.delete(n)
        self.assertFalse(os.path.exists(os.path.join(self.dir, "x.3mf")))
        self.assertEqual(os.listdir(os.path.join(self.root, "files")), [])
        with self.assertRaises(library.InvalidName):
            self.lib._path_for("../x.3mf")

    def test_a_symlink_in_the_files_folder_is_never_served(self):
        self.lib.add_bytes("a.3mf", make_3mf())
        secret = os.path.join(self.dir, "secret.txt")
        wr(secret, "nope")
        p = self.lib.file_path("a.3mf")
        os.remove(p)
        os.symlink(secret, p)
        with self.assertRaises(library.NotFound):
            self.lib.file_path("a.3mf")

    def test_delete_removes_file_thumb_and_index_entry(self):
        e = self.lib.add_bytes("a.3mf", make_3mf())
        thumb = os.path.join(self.root, "thumbs", e["thumb"])
        self.assertTrue(os.path.isfile(thumb))
        self.lib.delete("a.3mf")
        self.assertFalse(os.path.exists(thumb))
        self.assertFalse(os.path.exists(os.path.join(self.root, "files", "a.3mf")))
        with self.assertRaises(library.NotFound):
            self.lib.get("a.3mf")
        # a fresh Library object (a restart) sees the same, persisted state
        self.assertEqual(library.Library(self.root).entries(), [])

    def test_index_survives_a_restart_and_a_missing_file_drops_out(self):
        self.lib.add_bytes("a.3mf", make_3mf())
        self.lib.add_bytes("b.3mf", make_3mf(grams=1.0))
        again = library.Library(self.root)
        self.assertEqual([e["name"] for e in again.entries()], ["a.3mf", "b.3mf"])
        os.remove(os.path.join(self.root, "files", "a.3mf"))
        self.assertEqual([e["name"] for e in again.entries()], ["b.3mf"])

    def test_a_corrupt_index_is_kept_aside_and_the_library_starts_clean(self):
        os.makedirs(self.root, exist_ok=True)
        wr(os.path.join(self.root, "index.json"), "{not json")
        lib = library.Library(self.root)
        self.assertEqual(lib.entries(), [])
        self.assertTrue(os.path.exists(os.path.join(self.root, "index.json.bad")))

    def test_folders_create_move_delete(self):
        self.lib.add_bytes("a.3mf", make_3mf())
        self.assertEqual(self.lib.create_folder("Stands"), "Stands")
        with self.assertRaises(library.Exists):
            self.lib.create_folder("stands")
        self.lib.move("a.3mf", "stands")
        self.assertEqual(self.lib.get("a.3mf")["folder"], "Stands")
        with self.assertRaises(library.LibraryError):
            self.lib.delete_folder("Stands")                  # not empty
        self.lib.move("a.3mf", "")
        self.assertEqual(self.lib.delete_folder("Stands"), "Stands")
        with self.assertRaises(library.NotFound):
            self.lib.move("a.3mf", "Nope")
        e = self.lib.add_bytes("b.3mf", make_3mf(), folder="New one")        # an upload into a new folder creates it
        self.assertIn("New one", self.lib.folders())
        self.assertEqual(e["folder"], "New one")


