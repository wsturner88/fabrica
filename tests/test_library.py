class FakeBambu:
    kind = "bambu"
    has_camera = False
    uses_files_api = False

    def __init__(self, name, model="Bambu Lab P1S", state="IDLE"):
        self.name, self.model, self.serial = name, model, ""
        self.state = state
        self.files = {}               # filename -> bytes on the "card"
        self.cached = []              # the last idle listing the Hub saw
        self.ftps_opens = 0
        self.uploads, self.downloads, self.started = [], [], []

    def snapshot(self):
        return {"printer": self.name, "connected": True, "state": self.state, "job": "", "percent": 0,
                "remaining_min": None}

    def refresh(self, wait=0):
        pass

    def ams_trays(self):
        return []

    def _ftps(self):                  # what the real driver does first: refuse unless positively idle
        if self.state not in ("IDLE", "FINISH", "FAILED"):
            raise PrinterBusy(f"printer is busy ({self.name}: state {self.state}) - no FTPS session was opened.")
        self.ftps_opens += 1

    def sd_list(self):
        self._ftps()
        rows = [{"name": n, "size": len(b), "modified": ""} for n, b in self.files.items()]
        self.cached = rows
        return [dict(r) for r in rows]

    def sd_listing_cached(self):
        return [dict(r) for r in self.cached]

    def sd_upload(self, filename, data):
        self._ftps()
        self.files[filename] = data
        self.uploads.append(filename)

    def sd_download(self, filename):
        self._ftps()
        self.downloads.append(filename)
        return self.files[filename]

    def start_print(self, filename, ams_mapping):
        self.started.append((filename, list(ams_mapping)))


class _Resp:
    def __init__(self, data):
        self._b = io.BytesIO(data)

    def __enter__(self):
        return self

    def __exit__(self, *a):
        return False

    def read(self, n=-1):
        return self._b.read(n)


