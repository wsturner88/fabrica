def make_3mf(model_id="C12", model_name="Bambu Lab P1S", grams=12.5, secs=3900, color="#FF0000", png=True,
             extras=True, pad=0) -> bytes:
    code = f'<metadata key="printer_model_id" value="{model_id}"/>' if model_id is not None else ""
    info = ('<?xml version="1.0" encoding="UTF-8"?><config><header>'
            '<header_item key="X-BBL-Client-Type" value="slicer"/></header><plate>'
            '<metadata key="index" value="1"/>' + code +
            f'<metadata key="prediction" value="{secs}"/><metadata key="weight" value="{grams}"/>'
            '<metadata key="support_used" value="false"/><metadata key="nozzle_diameters" value="0.4"/>'
            f'<filament id="1" tray_info_idx="GFA00" type="PLA" color="{color}" used_m="1.0" used_g="3.0"/>'
            f'<filament id="2" tray_info_idx="GFA00" type="PETG" color="#0A2989" used_m="1.0" used_g="9.5"/>'
            '</plate></config>')
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        z.writestr("Metadata/slice_info.config", info)
        settings = {"printer_model": model_name}
        if extras:
            settings.update({"layer_height": "0.2", "nozzle_diameter": ["0.4"], "nozzle_temperature": ["220", "245"],
                             "curr_bed_type": "Textured PEI Plate", "textured_plate_temp": ["55", "70"],
                             "sparse_infill_density": "15%", "enable_support": "1"})
        z.writestr("Metadata/project_settings.config", json.dumps(settings))
        z.writestr("3D/3dmodel.model", '<?xml version="1.0"?><model><metadata name="Application">BambuStudio-01.10.01.50</metadata></model>')
        z.writestr("Metadata/plate_1.gcode", "; HEADER_BLOCK_START\n; total layer number: 69\nG28\n")
        if png:
            z.writestr("Metadata/plate_1.png", PNG)
        if pad:
            z.writestr("Metadata/pad.bin", os.urandom(pad))
    return buf.getvalue()


def make_gcode(model="MK4S", big=False) -> bytes:
    head = (b"; generated by PrusaSlicer 2.7.1 on 2026-10-01 at 10:00:00 UTC\n; printer_model = " + model.encode() +
            b"\nG28\n")
    body = b"G1 X1 Y1\n" * (150000 if big else 10)
    tail = (b"; estimated printing time (normal mode) = 1h 5m 3s\n; total filament used [g] = 12.30\n"
            b"; layer_height = 0.15\n; nozzle_diameter = 0.4\n; fill_density = 20%\n; support_material = 0\n"
            b"; temperature = 215\n; bed_temperature = 60\n; filament_type = PLA\n; filament_colour = #00FF00\n"
            b"; filament used [g] = 12.30\n")
    return head + body + tail


