class TestNames(unittest.TestCase):
    def test_good_names_pass(self):
        for n in ("Phone Stand v3.3mf", "Phone Stand v3.gcode.3mf", "part (2) [final].gcode", "a-b_c+d.bgcode",
                  "Ständer v2.gcode.3mf", "x'y&z, #1.3MF"):
            self.assertEqual(library.sanitize_name(n), n)

    def test_traversal_hidden_and_odd_names_are_refused(self):
        bad = ["../x.3mf", "..\\x.3mf", "a/b.3mf", "a\\b.3mf", "/etc/passwd.3mf", ".hidden.3mf", ".3mf", "x..3mf",
               "x.3mf.", "", "   ", "a\x00b.3mf", "a\nb.3mf", "a\tb.3mf", "x.txt", "x", "x.3mf.exe",
               "a:b.3mf", "a*b.3mf", 'a"b.3mf', "a<b>.3mf", "a|b.3mf", "a?b.3mf", "‮x.3mf", "a" * 130 + ".3mf",
               "é" * 110 + ".3mf", None, 7, ["x.3mf"]]
        for n in bad:
            with self.subTest(name=n):
                with self.assertRaises(library.InvalidName):
                    library.sanitize_name(n)

    def test_printer_paths_become_one_safe_name(self):
        self.assertEqual(library.name_from_printer_path("cache/Job One.gcode.3mf"), "Job One.gcode.3mf")
        self.assertEqual(library.name_from_printer_path("../../etc/evil.3mf"), "evil.3mf")
        self.assertEqual(library.name_from_printer_path("a:b*c.3mf"), "a_b_c.3mf")
        with self.assertRaises(library.InvalidName):
            library.name_from_printer_path("folder/readme.txt")

    def test_folders(self):
        self.assertEqual(library.sanitize_folder(""), "")
        self.assertEqual(library.sanitize_folder(None), "")
        self.assertEqual(library.sanitize_folder("  Stands & Holders "), "Stands & Holders")
        for bad in ("a/b", "..", ".x", "a.b", "x" * 41, "a\x00", "a\\b", "a:b", 5):
            with self.subTest(folder=bad):
                with self.assertRaises(library.InvalidName):
                    library.sanitize_folder(bad)

    def test_kinds(self):
        self.assertEqual(library.kind_of("x.gcode.3mf"), "3mf")
        self.assertEqual(library.kind_of("X.3MF"), "3mf")
        self.assertEqual(library.kind_of("x.gcode"), "gcode")
        self.assertEqual(library.kind_of("x.bgcode"), "bgcode")
        self.assertEqual(library.kind_of("x.zip"), "")


