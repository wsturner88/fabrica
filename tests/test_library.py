    def test_mcp_scopes_end_to_end(self):
        def rpc(method, params=None, id_=1):
            return {"jsonrpc": "2.0", "id": id_, "method": method, "params": params or {}}
        mh = {"Accept": "application/json, text/event-stream", "Content-Type": "application/json"}

        def session(h):
            r = self.c.post("/mcp", headers={**mh, **h}, json=rpc("initialize", {"protocolVersion": "2025-03-26", "capabilities": {},
                                                                                "clientInfo": {"name": "t", "version": "1"}}))
            self.assertEqual(r.status_code, 200, r.text)
            hh = {**mh, **h, "mcp-session-id": r.headers["mcp-session-id"], "mcp-protocol-version": "2025-03-26"}
            self.c.post("/mcp", headers=hh, json={"jsonrpc": "2.0", "method": "notifications/initialized"})
            return hh

        def call(hh, tool, args):
            r = self.c.post("/mcp", headers=hh, json=rpc("tools/call", {"name": tool, "arguments": args}, 5))
            self.assertEqual(r.status_code, 200, r.text)
            text = r.text
            if not r.headers.get("content-type", "").startswith("application/json"):
                text = next(l[5:] for l in r.text.splitlines() if l.startswith("data:"))
            return json.loads(text)["result"]
        rd = session(self.rd)
        out = call(rd, "library_list", {})
        self.assertFalse(out.get("isError"))
        self.assertIn("a.3mf", out["content"][0]["text"])
        self.assertIn("a.3mf", call(rd, "library_file", {"name": "a.3mf"})["content"][0]["text"])
        for tool, args in (("library_send", {"name": "a.3mf", "printers": ["P1S"]}),
                           ("library_save_from_printer", {"printer": "P1S", "filename": "a.3mf"})):
            res = call(rd, tool, args)
            self.assertTrue(res["isError"], tool)
            self.assertIn("needs a 'control' key", res["content"][0]["text"])
        self.assertEqual((self.p1s.uploads, self.p1s.ftps_opens), ([], 0))
        ct = session(self.ct)
        res = call(ct, "library_send", {"name": "a.3mf", "printers": ["P1S"]})
        self.assertFalse(res.get("isError"))
        self.assertEqual(json.loads(res["content"][0]["text"])["results"][0]["status"], "sent")
        self.assertEqual(self.p1s.started, [])


