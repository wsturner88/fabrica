def _3mf():
    b = io.BytesIO()
    with zipfile.ZipFile(b, "w") as z:
        z.writestr("Metadata/x.txt", "a")
    return b.getvalue()


class FakeBambu:
    """An SD card that ignores case (FAT / exFAT): STOR of 'a.3mf' replaces 'A.3mf'."""
    kind = "bambu"; has_camera = False; uses_files_api = False

    def __init__(s, name):
        s.name, s.model, s.serial, s.files, s.cached, s.ops = name, "Bambu Lab P1S", "", {}, [], []

    def snapshot(s): return {"printer": s.name, "connected": True, "state": "IDLE", "job": ""}
    def sd_list(s):
        s.cached = [{"name": n, "size": len(b)} for n, b in s.files.items()]
        return [dict(r) for r in s.cached]
    def sd_listing_cached(s): return list(s.cached)
    def sd_upload(s, fn, data):
        s.ops.append(("upload", fn))
        for k in list(s.files):
            if k.lower() == fn.lower():
                del s.files[k]
        s.files[fn] = data
    def sd_download(s, fn): return s.files[fn]


class FakeHttp:
    kind = "moonraker"; has_camera = False; uses_files_api = True; backup_mid_print_ok = True

    def __init__(s, name):
        s.name, s.model, s.files_map, s.ops, s.list_fails, s.body_bytes = name, "Voron 2.4", {}, [], False, 0

    def snapshot(s): return {"printer": s.name, "connected": True, "state": "IDLE", "job": ""}
    fresh_snapshot = snapshot
    def files(s, with_meta=True):
        if s.list_fails:
            raise OSError("timed out")
        return [{"name": n, "size": len(b), "origin": "local"} for n, b in s.files_map.items()]
    def upload(s, fn, data):
        s.ops.append(("upload", fn)); s.files_map[fn] = bytes(data)
    def download(s, fn, max_bytes=0): return s.files_map[fn]
    def open_file(s, fn, timeout=30):
        outer = s

        class R:
            def __enter__(r): return r
            def __exit__(r, *a): pass
            def read(r, k):
                if outer.body_bytes >= 8 * 1048576:
                    return b""
                outer.body_bytes += k
                return b"G1 X0\n" * (k // 6)
        return R()


def gcode(tag): return b"; generated by PrusaSlicer 2.7\n" + tag * 100


class SendCase(unittest.TestCase):
    def setUp(self):
        self._names = []
        server.PRINTERS.clear()

    def tearDown(self):
        server.PRINTERS.clear()
        for n in self._names:
            try:
                server.LIB.delete(n)
            except Exception:
                pass

    def lib(self, name, data):
        server.LIB.add_bytes(name, data)
        self._names.append(name)

    # ---- F1
    def test_f1_case_differing_name_on_card_is_never_overwritten(self):
        b = FakeBambu("P1"); server.PRINTERS["p1"] = b
        b.files["Bracket.3mf"] = b"OTHER FILE ON CARD" * 3
        self.lib("bracket.3mf", _3mf())
        res = server._library_send(["bracket.3mf"], ["P1"])
        self.assertEqual(res[0]["status"], "refused")
        self.assertEqual(res[0]["code"], "name_taken")
        self.assertEqual(b.ops, [])
        self.assertEqual(b.files, {"Bracket.3mf": b"OTHER FILE ON CARD" * 3})

    def test_f1_same_size_other_case_is_name_taken_not_already_there(self):
        b = FakeBambu("P1"); server.PRINTERS["p1"] = b
        data = _3mf()
        self.lib("cube.3mf", data)
        b.files["CUBE.3mf"] = b"x" * len(data)
        res = server._library_send(["cube.3mf"], ["P1"])
        self.assertEqual((res[0]["status"], res[0]["code"]), ("refused", "name_taken"))
        self.assertEqual(b.ops, [])

    def test_f1_exact_same_file_is_still_already_there(self):
        b = FakeBambu("P1"); server.PRINTERS["p1"] = b
        data = _3mf()
        self.lib("same.3mf", data)
        b.files["same.3mf"] = data
        res = server._library_send(["same.3mf"], ["P1"])
        self.assertEqual(res[0]["status"], "already_there")
        self.assertEqual(b.ops, [])

    def test_f1_free_name_still_sends(self):
        b = FakeBambu("P1"); server.PRINTERS["p1"] = b
        self.lib("fresh.3mf", _3mf())
        res = server._library_send(["fresh.3mf"], ["P1"])
        self.assertEqual(res[0]["status"], "sent")

    def test_f1_http_printer_case_differing_name_refused(self):
        h = FakeHttp("Klip"); server.PRINTERS["klip"] = h
        h.files_map["Part.gcode"] = gcode(b"ORIGINAL ")
        self.lib("part.gcode", gcode(b"LIBRARY-COPY-DIFFERENT "))
        res = server._library_send(["part.gcode"], ["Klip"])
        self.assertEqual((res[0]["status"], res[0]["code"]), ("refused", "name_taken"))
        self.assertEqual(h.ops, [])
        self.assertIn(b"ORIGINAL", h.files_map["Part.gcode"])

    # ---- F2
    def test_f2_failed_live_listing_refuses_http_send(self):
        h = FakeHttp("Klip"); server.PRINTERS["klip"] = h
        h.files_map["part.gcode"] = gcode(b"PRINTER-ORIGINAL ")
        self.lib("part.gcode", gcode(b"LIBRARY-COPY-DIFFERENT "))
        server._FILES_SEEN.pop("klip", None)                    # the cache is empty - the old code treated that as "free"
        h.list_fails = True
        res = server._library_send(["part.gcode"], ["Klip"])
        self.assertEqual((res[0]["status"], res[0]["code"]), ("refused", "list_failed"))
        self.assertEqual(h.ops, [])
        self.assertIn(b"PRINTER-ORIGINAL", h.files_map["part.gcode"])

    def test_f2_cache_is_not_trusted_even_when_it_says_free(self):
        h = FakeHttp("Klip"); server.PRINTERS["klip"] = h
        h.files_map["part.gcode"] = gcode(b"PRINTER-ORIGINAL ")
        self.lib("part.gcode", gcode(b"LIBRARY-COPY-DIFFERENT "))
        server._FILES_SEEN["klip"] = {}
        h.list_fails = True
        res = server._library_send(["part.gcode"], ["Klip"])
        self.assertEqual(res[0]["code"], "list_failed")
        self.assertEqual(h.ops, [])

    def test_f2_live_listing_ok_sends(self):
        h = FakeHttp("Klip"); server.PRINTERS["klip"] = h
        self.lib("new.gcode", gcode(b"X "))
        res = server._library_send(["new.gcode"], ["Klip"])
        self.assertEqual(res[0]["status"], "sent")
        self.assertEqual(h.ops, [("upload", "new.gcode")])

    # ---- F3
    def test_f3_http_save_stops_streaming_at_the_cap(self):
        h = FakeHttp("Klip2"); server.PRINTERS["klip2"] = h
        h.files_map["small.gcode"] = b"x" * 100                # the listing lies: 100 B, the body is 8 MB
        with self.assertRaises(library.TooLarge):
            server._library_save("Klip2", "small.gcode")
        self.assertLessEqual(h.body_bytes, 1048576 + 2 * 1048576, "kept reading long after the cap")
        self.assertLess(h.body_bytes, 8 * 1048576)
        inc = server.LIB.incoming
        self.assertEqual([f for f in os.listdir(inc) if f.startswith(".dl-")], [], "partial download left behind")
        with self.assertRaises(library.NotFound):
            server.LIB.get("small.gcode")

    def test_f3_stream_to_temp_cap(self):
        import backup

        class Resp:
            n = 0
            def __enter__(s): return s
            def __exit__(s, *a): pass
            def read(s, k):
                Resp.n += k
                return b"y" * k
        d = tempfile.mkdtemp(prefix="stt-")
        with self.assertRaises(backup.StreamTooLarge):
            backup._stream_to_temp(Resp(), d, max_bytes=3 * 1048576)
        self.assertEqual(os.listdir(d), [])
        self.assertLessEqual(Resp.n, 3 * 1048576 + 2 * 1048576)

    def test_f3_bambu_sd_download_cap(self):
        class FTP:
            def __init__(s): s.sent = 0
            def retrbinary(s, cmd, cb):
                for _ in range(100):
                    s.sent += 1000
                    cb(b"z" * 1000)
            def quit(s): pass
            def close(s): pass
        ftp = FTP()
        fake = types.SimpleNamespace(_ftps=lambda: ftp)
        with self.assertRaises(PrinterError):
            bambu.BambuPrinter.sd_download(fake, "a.3mf", max_bytes=5000)
        self.assertLess(ftp.sent, 10000)
        ftp2 = FTP()
        out = bambu.BambuPrinter.sd_download(types.SimpleNamespace(_ftps=lambda: ftp2), "a.3mf", max_bytes=200000)
        self.assertEqual(len(out), 100000)

    def test_f3_bambu_save_over_cap_is_refused(self):
        b = FakeBambu("P1"); server.PRINTERS["p1"] = b
        b.files["big.3mf"] = b"q" * (2 * 1048576)               # listing says 2 MB: refused before any download
        with self.assertRaises(library.TooLarge):
            server._library_save("P1", "big.3mf")
        # a card that under-reports its size: the returned bytes are still checked
        b.files["lie.3mf"] = b"q" * (2 * 1048576)
        b.sd_list = lambda: [{"name": "lie.3mf", "size": 10}]
        with self.assertRaises(library.TooLarge):
            server._library_save("P1", "lie.3mf")


class ZipBounds(unittest.TestCase):
    def test_f4_slice_info_bomb_is_capped(self):
        b = io.BytesIO()
        with zipfile.ZipFile(b, "w", zipfile.ZIP_DEFLATED) as z:
            z.writestr("Metadata/slice_info.config", b"\0" * (12 * 1048576))
        info = joblog.slice_info_from_3mf(b.getvalue())
        self.assertEqual(info["plates"], [])
        self.assertIn("unreadable", info["error"])

    def test_f4_normal_slice_info_still_parses(self):
        b = io.BytesIO()
        with zipfile.ZipFile(b, "w") as z:
            z.writestr("Metadata/slice_info.config",
                       '<config><plate><metadata key="index" value="1"/></plate></config>')
        self.assertEqual(len(joblog.slice_info_from_3mf(b.getvalue())["plates"]), 1)

    def _many(self, n):
        b = io.BytesIO()
        with zipfile.ZipFile(b, "w", zipfile.ZIP_STORED) as z:
            for i in range(n):
                z.writestr(str(i), b"")
        return b.getvalue()

    def test_f5_too_many_entries_refused_before_zipfile_parses_them(self):
        data = self._many(20000)
        with self.assertRaises(ValueError):
            bambu.open_zip_bounded(data)
        self.assertIn("error", bambu.parse_3mf_meta(data))
        self.assertEqual(joblog.slice_info_from_3mf(data)["plates"], [])
        p = os.path.join(tempfile.mkdtemp(prefix="many-"), "many.3mf")
        with open(p, "wb") as fh:
            fh.write(data)
        with mock.patch("zipfile.ZipFile", side_effect=AssertionError("ZipFile built the whole directory")):
            meta, png = library.extract_meta(p, "3mf")
        self.assertIn("error", meta)

    def test_f5_normal_3mf_opens(self):
        z = bambu.open_zip_bounded(self._many(50))
        self.assertEqual(len(z.namelist()), 50)


class RenameTicketAndDelete(unittest.TestCase):
    # ---- F7
    def test_f7_library_rename_with_changed_file_is_skipped(self):
        server.LIB.add_bytes("before.gcode", gcode(b"A "))
        try:
            old_size = server.LIB.get("before.gcode")["size"]
            server.LIB.add_bytes("before.gcode", gcode(b"B-DIFFERENT-LENGTH " * 3), replace=True)
            it = {"location": "library", "old_name": "before.gcode", "new_name": "after.gcode", "size": old_size}
            r = server._rn_apply_library(it)
            self.assertEqual(r["status"], "skipped")
            self.assertEqual(server.LIB.get("before.gcode")["name"], "before.gcode")
            with self.assertRaises(library.NotFound):
                server.LIB.get("after.gcode")
        finally:
            for n in ("before.gcode", "after.gcode"):
                try:
                    server.LIB.delete(n)
                except Exception:
                    pass

    def test_f7_library_rename_with_matching_size_works(self):
        server.LIB.add_bytes("one.gcode", gcode(b"A "))
        try:
            it = {"location": "library", "old_name": "one.gcode", "new_name": "two.gcode",
                  "size": server.LIB.get("one.gcode")["size"]}
            self.assertEqual(server._rn_apply_library(it)["status"], "renamed")
        finally:
            for n in ("one.gcode", "two.gcode"):
                try:
                    server.LIB.delete(n)
                except Exception:
                    pass

    # ---- F6
    def test_f6_octoprint_delete_refused_when_not_idle(self):
        p = bambu.OctoPrintPrinter("o", "http://127.0.0.1:9", "k")
        busy = lambda: {"connected": True, "state": "PRINTING"}
        p.snapshot = busy
        p.fresh_snapshot = busy
        called = []
        p._delete = lambda path: called.append(path)
        with self.assertRaises(PrinterBusy):
            p.sd_delete("x.gcode")
        self.assertEqual(called, [])

    def test_f6_octoprint_delete_when_idle_goes_through(self):
        p = bambu.OctoPrintPrinter("o", "http://127.0.0.1:9", "k")
        idle = lambda: {"connected": True, "state": "IDLE"}
        p.snapshot = idle
        p.fresh_snapshot = idle
        called = []
        p._delete = lambda path: called.append(path)
        p.sd_delete("x.gcode")
        self.assertEqual(len(called), 1)


