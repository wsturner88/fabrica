def make_3mf(model_id="C12", model_name="Bambu Lab P1S", with_settings=True) -> bytes:
    """A minimal sliced .3mf: slice_info.config (+ project_settings.config) and one used filament."""
    code = f'<metadata key="printer_model_id" value="{model_id}"/>' if model_id is not None else ""
    info = ('<?xml version="1.0" encoding="UTF-8"?><config><plate>'
            '<metadata key="index" value="1"/>' + code +
            '<metadata key="prediction" value="3600"/><metadata key="weight" value="12.5"/>'
            '<filament id="1" tray_info_idx="GFA00" type="PLA" color="#FF0000" used_m="1.0" used_g="3.0"/>'
            '</plate></config>')
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        z.writestr("Metadata/slice_info.config", info)
        if with_settings:
            z.writestr("Metadata/project_settings.config", json.dumps(
                {"printer_model": model_name, "printer_settings_id": model_name + " 0.4 nozzle"}))
        z.writestr("Metadata/plate_1.gcode", "G28\n")
    return buf.getvalue()


def prusa_head(model="MK4S", style="comment") -> bytes:
    if style == "comment":
        return (b"; generated by PrusaSlicer 2.7.1\n; printer_model = " + model.encode() +
                b"\n; printer_settings_id = Original Prusa " + model.encode() + b" 0.4 nozzle\nG28\n")
    return b'; generated by PrusaSlicer\nM862.3 P "' + model.encode() + b'" ; printer model check\nG28\n'


