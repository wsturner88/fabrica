class FakeBambu:
    kind = "bambu"
    has_camera = False
    uses_files_api = False

    def __init__(self, name, model="Bambu Lab A1", serial="03900000000000A"):
        self.name, self.model, self.serial = name, model, serial
        self.files = {}               # filename -> bytes
        self.downloads = 0
        self.started = []

    def snapshot(self):
        return {"printer": self.name, "connected": True, "state": "IDLE", "job": "", "percent": 0,
                "remaining_min": None}

    def refresh(self, wait=0):
        pass

    def ams_trays(self):
        return [{"tray": 0, "slot_1based": 1, "type": "PLA", "color": "#FF0000"}]

    def sd_list(self):
        return [{"name": n, "size": len(b), "modified": ""} for n, b in self.files.items()]

    def sd_download(self, filename):
        self.downloads += 1
        return self.files[filename]

    def start_print(self, filename, ams_mapping):
        self.started.append((filename, list(ams_mapping)))


class FakeGcodePrinter:
    kind = "prusalink"
    has_camera = False
    uses_files_api = True

    def __init__(self, name, model="Original Prusa MK4S"):
        self.name, self.model = name, model
        self.files_map = {}
        self.head_reads = 0
        self.started = []

    def snapshot(self):
        return {"printer": self.name, "connected": True, "state": "IDLE", "job": "", "percent": 0,
                "remaining_min": None}

    def refresh(self, wait=0):
        pass

    def ams_trays(self):
        return []

    def files(self):
        return [{"name": n, "size": len(b), "print_time": "1h00m"} for n, b in self.files_map.items()]

    def download_head(self, filename, nbytes=1048576):
        self.head_reads += 1
        return self.files_map[filename][:nbytes]

    def start_print(self, filename, ams_mapping=None, origin="local"):
        self.started.append(filename)


