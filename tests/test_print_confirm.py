class TestCodeTable(unittest.TestCase):
    # source: Bambu Studio resources/profiles/BBL/machine/<model>.json "model_id" (verified 2026-10-11)
    VERIFIED = {"BL-P001": "X1 Carbon", "BL-P002": "X1", "C13": "X1E", "C11": "P1P", "C12": "P1S",
                "N1": "A1 mini", "N2S": "A1", "O1D": "H2D", "O1E": "H2D Pro", "O1S": "H2S",
                "O1C2": "H2C", "N7": "P2S", "N6": "X2D", "N9": "A2L"}

    def test_every_verified_code_maps_to_its_model(self):
        for code, short in self.VERIFIED.items():
            with self.subTest(code=code):
                got = modelcheck.model_for_code(code)
                self.assertIsNotNone(got)
                self.assertEqual(got[0], short)
                self.assertEqual(got[1], "Bambu Lab " + short)

    def test_lookup_is_case_and_space_tolerant_and_unknown_is_none(self):
        self.assertEqual(modelcheck.model_for_code(" c12 ")[0], "P1S")
        for bad in (None, "", "ZZZ", "C99"):
            self.assertIsNone(modelcheck.model_for_code(bad))

    def test_codes_are_unique_per_model(self):
        shorts = {}
        for code, (short, _full) in modelcheck.BAMBU_MODEL_IDS.items():
            shorts.setdefault(short, set()).add(code)
        self.assertEqual(len(modelcheck.BAMBU_MODEL_IDS) - len(shorts), 1)    # only H2C has an alias


class TestNames(unittest.TestCase):
    def test_same_model_matrix(self):
        same = [("P1S", "Bambu Lab P1S"), ("Bambu Lab X1 Carbon", "X1C"), ("A1 mini", "Bambu Lab A1 mini"),
                ("MK4", "Original Prusa MK4S"), ("MK3S+", "Original Prusa MK3S"),
                ("Original Prusa MK4S HF0.4 nozzle", "MK4S"), ("Bambu Lab P1S 0.4 nozzle", "P1S"),
                ("Voron 2.4", "Voron 2.4 300mm")]
        for a, b in same:
            with self.subTest(a=a, b=b):
                self.assertIs(modelcheck.same_model(a, b), True)

    def test_different_models(self):
        diff = [("P1S", "A1"), ("A1", "A1 mini"), ("P1P", "P1S"), ("X1", "X1C"), ("H2D", "H2S"),
                ("MK4S", "MK3S"), ("MK4S", "MINI"), ("P1S", "MK4S"), ("Bambu Lab A1", "Original Prusa MK4S")]
        for a, b in diff:
            with self.subTest(a=a, b=b):
                self.assertIs(modelcheck.same_model(a, b), False)

    def test_unknown_when_either_side_is_blank(self):
        for a, b in (("", "A1"), ("A1", ""), (None, None), ("   ", "P1S")):
            self.assertIsNone(modelcheck.same_model(a, b))

    def test_check_payload(self):
        r = modelcheck.check("Bambu Lab P1S", "Bambu Lab A1")
        self.assertIs(r["model_match"], False)
        self.assertEqual((r["sliced_for"], r["target_model"]), ("P1S", "A1"))
        self.assertEqual(r["model_warning"],
                         "THIS FILE WAS SLICED FOR P1S — YOU ARE ON A1. Printing it could damage the printer.")
        ok = modelcheck.check("Bambu Lab A1", "A1")
        self.assertIs(ok["model_match"], True)
        self.assertIsNone(ok["model_warning"])
        unk = modelcheck.check("", "A1")
        self.assertEqual(unk["model_match"], "unknown")
        self.assertEqual(unk["model_warning"], "Couldn't tell which printer this was sliced for.")

    def test_hostile_model_text_is_cleaned(self):
        r = modelcheck.check('<img src=x onerror=alert(1)>MK4S" & ' + "Z" * 200, "A1")
        for k in ("sliced_for", "model_warning"):
            self.assertNotIn("<", r[k] or "")
            self.assertNotIn('"', r[k] or "")
        self.assertLessEqual(len(r["sliced_for"]), 40)


class TestFileModels(unittest.TestCase):
    def test_bambu_meta_by_code(self):
        self.assertEqual(modelcheck.file_model_bambu({"printer_model_id": "C12"}), "Bambu Lab P1S")
        self.assertEqual(modelcheck.file_model_bambu({"printer_model_id": "N2S"}), "Bambu Lab A1")

    def test_bambu_meta_falls_back_to_the_name_for_an_unknown_code(self):
        self.assertEqual(modelcheck.file_model_bambu({"printer_model_id": "Q9", "printer_model": "Bambu Lab P1S"}),
                         "Bambu Lab P1S")
        self.assertEqual(modelcheck.file_model_bambu({"printer_model_id": "Q9"}), "")
        self.assertEqual(modelcheck.file_model_bambu({"printer_model_id": None}), "")
        self.assertEqual(modelcheck.file_model_bambu(None), "")

    def test_parse_3mf_meta_reads_code_and_name(self):
        m = parse_3mf_meta(make_3mf("C12", "Bambu Lab P1S"))
        self.assertEqual(m["printer_model_id"], "C12")
        self.assertEqual(m["printer_model"], "Bambu Lab P1S")
        m = parse_3mf_meta(make_3mf("N1", "Bambu Lab A1 mini", with_settings=False))
        self.assertEqual((m["printer_model_id"], m["printer_model"]), ("N1", None))
        m = parse_3mf_meta(make_3mf(None, with_settings=False))
        self.assertIsNone(m["printer_model_id"])

    def test_gcode_heads(self):
        cases = [(prusa_head("MK4S"), "MK4S"),
                 (prusa_head("MK4S", "m862"), "MK4S"),
                 (b"; HEADER_BLOCK_START\n; printer_settings_id = Bambu Lab A1 0.4 nozzle\nG28\n",
                  "Bambu Lab A1 0.4 nozzle"),
                 (b"GCDE\x01\x00printer_model=MK4S\nnozzle_diameter=0.4\x00\x00binary", "MK4S"),
                 (b'M862.3 P "[printer_model]" ; unexpanded\nG28\n', ""),
                 (b"; printer_model =\n; layer_height = 0.2\n", ""),
                 (b"G28\nG1 X10\n", ""), (b"", ""), (None, "")]
        for data, want in cases:
            with self.subTest(data=data):
                self.assertEqual(modelcheck.gcode_head_model(data), want)

    def test_gcode_head_ignores_a_value_on_the_next_line(self):
        self.assertEqual(modelcheck.gcode_head_model(b"; printer_model = \n; layer_height = 0.2\n"), "")


