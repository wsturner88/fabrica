@unittest.skipUnless(HAVE, "mcp + starlette + httpx needed to import the server")
class ServerBase(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.client = TestClient(server.mcp.streamable_http_app())

    def setUp(self):
        server.PRINTERS.clear()
        server._START_PENDING.clear()                       # the fakes never turn RUNNING, so a "start pending" would linger
        server.START_TICKETS.clear()
        try:
            os.remove(server.CACHE_PATH)
        except OSError:
            pass
        p = mock.patch.object(server.time, "sleep")        # start_print waits 8 s for the printer to react
        p.start()
        self.addCleanup(p.stop)
        self.a1 = FakeBambu("A1")
        server.PRINTERS["a1"] = self.a1

    def add_file(self, name, model_id, model_name=None, printer=None):
        prn = printer or self.a1
        prn.files[name] = make_3mf(model_id, model_name or "Bambu Lab P1S", with_settings=model_name is not None)
        return name

    def suggest(self, name, printer="A1"):
        r = self.client.post(f"/api/printer/{printer}/suggest", json={"filename": name})
        self.assertEqual(r.status_code, 200, r.text)
        return r.json()

    def start(self, name, d, printer="A1", **extra):
        body = {"filename": name, "ams_mapping": d["ams_mapping"], "confirm": d["confirm_string"],
                "plate_clear": True}
        body.update(extra)
        return self.client.post(f"/api/printer/{printer}/start", json=body)


class TestSuggestPayload(ServerBase):
    def test_match(self):
        self.add_file("ok.gcode.3mf", "N2S")
        d = self.suggest("ok.gcode.3mf")
        self.assertIs(d["model_match"], True)
        self.assertEqual((d["sliced_for"], d["target_model"], d["target_model_name"]), ("A1", "A1", "Bambu Lab A1"))
        self.assertIsNone(d["model_warning"])
        self.assertEqual(d["printer_kind"], "bambu")
        self.assertIsNone(d["blocked"])

    def test_mismatch(self):
        self.add_file("p1s.gcode.3mf", "C12")
        d = self.suggest("p1s.gcode.3mf")
        self.assertIs(d["model_match"], False)
        self.assertEqual((d["sliced_for"], d["target_model"]), ("P1S", "A1"))
        self.assertIn("THIS FILE WAS SLICED FOR P1S", d["model_warning"])
        self.assertIn("YOU ARE ON A1", d["model_warning"])
        self.assertIn("model_override", d["next_step"])
        self.assertTrue(d["confirm_string"].startswith("ph-"))      # a single-use ticket, not a guessable string
        self.assertNotIn("model_override", d["confirm_string"])      # the plain code: no override baked in

    def test_unknown_file_model(self):
        self.add_file("who.gcode.3mf", None)
        d = self.suggest("who.gcode.3mf")
        self.assertEqual(d["model_match"], "unknown")
        self.assertIsNone(d["sliced_for"])
        self.assertIn("Couldn't tell which printer this was sliced for", d["model_warning"])

    def test_unknown_target_model_is_not_a_block(self):
        self.a1.model, self.a1.serial = "", "ZZZ00000000000A"
        self.add_file("p1s.gcode.3mf", "C12")
        d = self.suggest("p1s.gcode.3mf")
        self.assertEqual(d["model_match"], "unknown")
        self.assertEqual(self.start("p1s.gcode.3mf", d).status_code, 200)

    def test_unknown_code_but_known_name(self):
        self.add_file("odd.gcode.3mf", "Q9", "Bambu Lab P1S")
        self.assertIs(self.suggest("odd.gcode.3mf")["model_match"], False)

    def test_mcp_suggest_text_carries_the_check(self):
        self.add_file("p1s.gcode.3mf", "C12")
        d = json.loads(server.suggest_mapping("A1", "p1s.gcode.3mf"))
        self.assertIs(d["model_match"], False)
        self.assertIn("MODEL MISMATCH", d["next_step"])

    def test_gcode_printer_payload(self):
        mk4 = FakeGcodePrinter("MK4")
        server.PRINTERS["mk4"] = mk4
        mk4.files_map["a.gcode"] = prusa_head("MK4S")
        mk4.files_map["b.gcode"] = prusa_head("XL")
        mk4.files_map["c.gcode"] = b"G28\nG1 X5\n"
        mk4.files_map["d.gcode"] = prusa_head("MK4S", "m862")
        a, b, c, dd = (self.suggest(n, "MK4") for n in ("a.gcode", "b.gcode", "c.gcode", "d.gcode"))
        self.assertIs(a["model_match"], True)
        self.assertEqual(a["printer_kind"], "prusalink")
        self.assertIs(b["model_match"], False)
        self.assertEqual(b["sliced_for"], "XL")
        self.assertEqual(c["model_match"], "unknown")
        self.assertIs(dd["model_match"], True)

    def test_gcode_head_is_read_once_and_cached_beside_the_thumbnail(self):
        mk4 = FakeGcodePrinter("MK4")
        server.PRINTERS["mk4"] = mk4
        mk4.files_map["a.gcode"] = prusa_head("MK4S")
        self.suggest("a.gcode", "MK4")
        self.suggest("a.gcode", "MK4")
        self.assertEqual(mk4.head_reads, 1)
        entry = server._cache_load()[f"MK4|a.gcode|{len(mk4.files_map['a.gcode'])}"]
        self.assertEqual(entry["slicer_model"], "MK4S")
        self.assertIn("thumb", entry)

    def test_bambu_file_is_downloaded_once_and_start_reads_only_the_cache(self):
        self.add_file("p1s.gcode.3mf", "C12")
        d = self.suggest("p1s.gcode.3mf")
        n = self.a1.downloads
        self.assertEqual(self.start("p1s.gcode.3mf", d).status_code, 409)
        self.assertEqual(self.a1.downloads, n)         # the authoritative re-check costs the printer nothing


class TestStartRefusal(ServerBase):
    def setUp(self):
        super().setUp()
        self.add_file("p1s.gcode.3mf", "C12")
        self.d = self.suggest("p1s.gcode.3mf")
        self.tag = "|" + modelcheck.MODEL_OVERRIDE_TAG

    def test_rest_start_refused_on_mismatch_without_override(self):
        r = self.start("p1s.gcode.3mf", self.d)
        self.assertEqual(r.status_code, 409)
        self.assertIn("SLICED FOR P1S", r.json()["error"])
        self.assertEqual(self.a1.started, [])

    def test_rest_start_accepted_with_override_and_tagged_confirm(self):
        r = self.start("p1s.gcode.3mf", self.d, confirm=self.d["confirm_string"] + self.tag, model_override=True)
        self.assertEqual(r.status_code, 200, r.text)
        self.assertEqual(self.a1.started, [("p1s.gcode.3mf", [0])])

    def test_override_flag_without_the_tag_is_refused(self):
        r = self.start("p1s.gcode.3mf", self.d, model_override=True)
        self.assertEqual(r.status_code, 409)
        self.assertIn("confirm string mismatch", r.json()["error"])
        self.assertEqual(self.a1.started, [])

    def test_replaying_an_override_confirm_without_the_flag_is_refused(self):
        r = self.start("p1s.gcode.3mf", self.d, confirm=self.d["confirm_string"] + self.tag)
        self.assertEqual(r.status_code, 409)
        self.assertIn("SLICED FOR P1S", r.json()["error"])
        self.assertEqual(self.a1.started, [])

    def test_override_must_be_exactly_true(self):
        r = self.start("p1s.gcode.3mf", self.d, confirm=self.d["confirm_string"] + self.tag, model_override="yes")
        self.assertEqual(r.status_code, 409)
        self.assertEqual(self.a1.started, [])

    def test_matching_file_does_not_accept_a_tagged_confirm_without_the_flag(self):
        self.add_file("ok.gcode.3mf", "N2S")
        d = self.suggest("ok.gcode.3mf")
        self.assertEqual(self.start("ok.gcode.3mf", d, confirm=d["confirm_string"] + self.tag).status_code, 409)
        self.assertEqual(self.start("ok.gcode.3mf", d).status_code, 200)
        self.assertEqual(self.a1.started, [("ok.gcode.3mf", [0])])

    def test_mcp_start_print_refusal_text(self):
        out = server.start_print("A1", "p1s.gcode.3mf", self.d["ams_mapping"], self.d["confirm_string"],
                                 bed_clear_confirmed_by_human=True)
        self.assertTrue(out.startswith("REFUSED"))
        self.assertIn("THIS FILE WAS SLICED FOR P1S", out)
        self.assertIn("model_override=True", out)
        self.assertEqual(self.a1.started, [])

    def test_mcp_start_print_with_override(self):
        out = server.start_print("A1", "p1s.gcode.3mf", self.d["ams_mapping"],
                                 self.d["confirm_string"] + self.tag, model_override=True,
                                 bed_clear_confirmed_by_human=True)
        self.assertIn('"sent": true', out)
        self.assertEqual(len(self.a1.started), 1)

    def test_mcp_docstring_tells_agents_to_ask_the_human(self):
        doc = server.start_print.__doc__
        self.assertIn("model_override", doc)
        self.assertIn("ask the human", doc.lower())

    def test_gcode_printer_mismatch_is_refused_and_overridable(self):
        mk4 = FakeGcodePrinter("MK4")
        server.PRINTERS["mk4"] = mk4
        mk4.files_map["x.gcode"] = prusa_head("XL")
        d = self.suggest("x.gcode", "MK4")
        self.assertEqual(self.start("x.gcode", d, "MK4").status_code, 409)
        self.assertEqual(mk4.started, [])
        r = self.start("x.gcode", d, "MK4", confirm=d["confirm_string"] + self.tag, model_override=True)
        self.assertEqual(r.status_code, 200, r.text)
        self.assertEqual(mk4.started, ["x.gcode"])

    def test_unknown_model_start_works_as_before(self):
        self.add_file("who.gcode.3mf", None)
        d = self.suggest("who.gcode.3mf")
        self.assertEqual(self.start("who.gcode.3mf", d).status_code, 200)

    def test_plate_clear_is_still_required(self):
        self.assertEqual(self.start("p1s.gcode.3mf", self.d, plate_clear=False).status_code, 400)


