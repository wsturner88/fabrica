class TestNames(unittest.TestCase):
    def probs(self, old, new):
        return renamer.name_problems(old, new)

    def test_extension_is_kept_whole(self):
        self.assertEqual(renamer.file_ext("a.gcode.3mf"), ".gcode.3mf")
        self.assertEqual(renamer.file_ext("a.v2.3mf"), ".3mf")
        self.assertEqual(renamer.file_ext("noext"), "")
        self.assertEqual(self.probs("a.gcode.3mf", "b.gcode.3mf"), [])
        self.assertTrue(self.probs("a.gcode.3mf", "b.3mf"))          # .gcode.3mf must stay .gcode.3mf
        self.assertTrue(self.probs("a.3mf", "b.gcode.3mf"))
        self.assertTrue(self.probs("a.gcode", "b.bgcode"))
        self.assertTrue(self.probs("a.3mf", "b.3MF"))                # capitals of the extension count too
        self.assertTrue(self.probs("a.3mf", "b"))

    def test_unsafe_characters_and_shapes(self):
        for ch in '/\\:*?"<>|':
            self.assertTrue(self.probs("a.3mf", f"x{ch}y.3mf"), ch)
        for bad in ("x\ny.3mf", "x\x00y.3mf", "x‮y.3mf", " x.3mf", "x .3mf", ".x.3mf", "x..3mf", "x. .3mf", ".3mf", "x" * 201 + ".3mf"):
            self.assertTrue(self.probs("a.3mf", bad), repr(bad))
        self.assertTrue(self.probs("a.3mf", "a.3mf"))               # same name
        self.assertTrue(self.probs("sub/a.3mf", "a.3mf"))
        self.assertEqual(self.probs("a.3mf", "Phone Stand v3 - 6X - P1S.3mf"), [])
        self.assertEqual(self.probs("a.3mf", "Name (copy) [2] #1 & more, ok.3mf"), [])   # no naming convention is enforced

    def test_target_keeps_the_folder(self):
        self.assertEqual(renamer.target_path("sub/a.gcode", "b.gcode"), "sub/b.gcode")
        self.assertEqual(renamer.target_path("a.gcode", "b.gcode"), "b.gcode")

    def test_parse_items(self):
        with self.assertRaises(renamer.RenameError):
            renamer.parse_items([])
        with self.assertRaises(renamer.RenameError):
            renamer.parse_items("x")
        with self.assertRaises(renamer.RenameError):
            renamer.parse_items([{"location": "P", "old_name": "a"}])
        with self.assertRaises(renamer.RenameError):
            renamer.parse_items([{"location": "P", "old_name": "a.3mf", "new_name": "b.3mf"}] * 101)
        got = renamer.parse_items([{"location": " P ", "old_name": "a.3mf", "new_name": "é.3mf"}])
        self.assertEqual((got[0]["location"], got[0]["new_name"]), ("P", "é.3mf"))       # NFC

    def test_ticket_single_use_expiry_and_binding(self):
        now = [1000.0]
        t = renamer.RenameTickets(ttl=600, clock=lambda: now[0])
        items = [{"location": "P", "old_name": "a.3mf", "new_name": "b.3mf", "size": 5}]
        n = t.issue(items, {"p": object()})
        self.assertTrue(n.startswith("rn-"))
        self.assertIsNone(t.peek("rn-guess")[0])
        got, why = t.peek(n)
        self.assertEqual(got["items"], items)
        got["items"][0]["new_name"] = "tampered.3mf"                          # the stored list no longer matches its fingerprint
        self.assertIsNone(t.peek(n)[0])
        n2 = t.issue(items, {})
        self.assertTrue(t.consume(n2))
        self.assertFalse(t.consume(n2))                                       # single use
        self.assertIn("already used", t.peek(n2)[1] or "already used")
        n3 = t.issue(items, {})
        now[0] += 601
        self.assertIsNone(t.peek(n3)[0])                                      # expired after 10 minutes
        self.assertNotIn(n3, t.peek(n3)[1])                                   # never echoes the code


