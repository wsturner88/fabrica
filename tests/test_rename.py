    def test_mcp_scopes_and_the_prompt(self):
        mh = {"Accept": "application/json, text/event-stream", "Content-Type": "application/json"}

        def session(h):
            r = self.c.post("/mcp", headers={**mh, **h}, json={"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {
                "protocolVersion": "2025-03-26", "capabilities": {}, "clientInfo": {"name": "t", "version": "1"}}})
            self.assertEqual(r.status_code, 200, r.text)
            hh = {**mh, **h, "mcp-session-id": r.headers["mcp-session-id"], "mcp-protocol-version": "2025-03-26"}
            self.c.post("/mcp", headers=hh, json={"jsonrpc": "2.0", "method": "notifications/initialized"})
            return hh

        def call(hh, tool, args):
            r = self.c.post("/mcp", headers=hh, json={"jsonrpc": "2.0", "id": 5, "method": "tools/call", "params": {"name": tool, "arguments": args}})
            text = r.text
            if not r.headers.get("content-type", "").startswith("application/json"):
                text = next(l[5:] for l in r.text.splitlines() if l.startswith("data:"))
            return json.loads(text)["result"]
        rh = session(self.rk)
        self.assertFalse(call(rh, "file_facts", {"location": "P1S", "filename": "A.gcode.3mf"}).get("isError"))
        item = {"location": "P1S", "old_name": "A.gcode.3mf", "new_name": "B.gcode.3mf"}
        for tool, args in (("rename_preview", {"renames": [item]}), ("rename_apply", {"ticket": "rn-x", "approved_by_human": True})):
            res = call(rh, tool, args)
            self.assertTrue(res["isError"], tool)
            self.assertIn("needs a 'control' key", res["content"][0]["text"])
        self.assertEqual(sorted(self.p1s.files), ["A.gcode.3mf"])
        ch = session(self.ck)
        pv = json.loads(call(ch, "rename_preview", {"renames": [item]})["content"][0]["text"])
        self.assertTrue(pv["ticket"])
        r = self.c.post("/mcp", headers=ch, json={"jsonrpc": "2.0", "id": 9, "method": "prompts/get", "params": {"name": "rename_files"}})
        self.assertEqual(r.status_code, 200, r.text)
        self.assertIn("approved_by_human", r.text)

