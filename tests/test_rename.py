class _FakeResp:
    def __init__(self, data=b"", status=200, headers=None):
        self._b, self.status, self.headers = io.BytesIO(data), status, headers or {}

    def __enter__(self):
        return self

    def __exit__(self, *a):
        return False

    def read(self, n=-1):
        return self._b.read(n)

    def close(self):
        pass


class _Opener:
    def __init__(self, resp=None, error=None):
        self.reqs, self.resp, self.error = [], resp, error

    def open(self, req, timeout=None):
        body = req.data.read() if hasattr(req.data, "read") else req.data
        self.reqs.append({"url": req.full_url, "method": req.get_method(), "headers": {k.lower(): v for k, v in req.header_items()},
                          "body": body, "timeout": timeout})
        if self.error:
            raise self.error
        return self.resp or _FakeResp(b"{}", 201)


