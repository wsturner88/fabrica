class FakeBambu:
    kind = "bambu"
    has_camera = False
    uses_files_api = False

    def __init__(self, name, model="Bambu Lab P1S", state="IDLE"):
        self.name, self.model, self.serial = name, model, ""
        self.state, self.job = state, ""
        self.files, self.cached = {}, []
        self.ftps_opens = 0
        self.ops, self.started = [], []
        self.upload_mode = "ok"            # ok | raise_partial | truncate | drop
        self.after_download = None

    def snapshot(self):
        return {"printer": self.name, "connected": True, "state": self.state, "job": self.job, "percent": 0, "remaining_min": None}

    def refresh(self, wait=0):
        pass

    def ams_trays(self):
        return []

    def _ftps(self):
        if self.state not in ("IDLE", "FINISH", "FAILED"):
            raise PrinterBusy(f"printer is busy ({self.name}: state {self.state}) - no FTPS session was opened.")
        self.ftps_opens += 1

    def sd_list(self):
        if self.state not in ("IDLE", "FINISH", "FAILED"):
            if self.cached:
                return [dict(r) for r in self.cached]
            raise PrinterBusy("The file list will appear when it finishes printing")
        self._ftps()
        self.ops.append("list")
        self.cached = [{"name": n, "size": len(b), "modified": ""} for n, b in self.files.items()]
        return [dict(r) for r in self.cached]

    def sd_listing_cached(self):
        return [dict(r) for r in self.cached]

    def sd_download(self, filename):
        self._ftps()
        self.ops.append("download")
        data = self.files[filename]
        if self.after_download:
            self.after_download()
        return data

    def sd_upload(self, filename, data):
        self._ftps()
        self.ops.append("upload")
        if self.upload_mode == "raise_partial":
            self.files[filename] = data[: len(data) // 2]
            raise PrinterError("connection reset")
        if self.upload_mode == "truncate":
            self.files[filename] = data[:-5]
        elif self.upload_mode == "ok":
            self.files[filename] = data

    def sd_delete(self, filename):
        self._ftps()
        self.ops.append("delete:" + filename)
        del self.files[filename]

    def start_print(self, *a, **k):
        self.started.append(a)


