class TestLibraryRename(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.mkdtemp(prefix="rn-lib-")
        self.addCleanup(shutil.rmtree, self.dir, True)
        self.lib = library.Library(os.path.join(self.dir, "library"))

    def test_rename_moves_file_preview_and_index_together_and_keeps_the_folder(self):
        self.lib.create_folder("Stands")
        e = self.lib.add_bytes("Old Name.3mf", make_3mf(), folder="Stands")
        old_thumb = e["thumb"]
        out = self.lib.rename("Old Name.3mf", "New Name.3mf")
        self.assertEqual((out["name"], out["folder"]), ("New Name.3mf", "Stands"))
        self.assertFalse(os.path.exists(os.path.join(self.lib.files_dir, "Old Name.3mf")))
        self.assertTrue(os.path.isfile(os.path.join(self.lib.files_dir, "New Name.3mf")))
        self.assertEqual([x["name"] for x in self.lib.entries()], ["New Name.3mf"])
        self.assertIsNotNone(self.lib.thumb_path(out["thumb"]))
        self.assertIsNone(self.lib.thumb_path(old_thumb))
        again = library.Library(os.path.join(self.dir, "library"))                    # persisted
        self.assertEqual([x["name"] for x in again.entries()], ["New Name.3mf"])
        self.assertEqual(again.get("New Name.3mf")["sha256"], e["sha256"])

    def test_refusals(self):
        self.lib.add_bytes("a.3mf", make_3mf(tag="a"))
        self.lib.add_bytes("b.3mf", make_3mf(tag="b"))
        for new, exc in (("b.3mf", library.Exists), ("B.3MF", library.LibraryError), ("a.gcode", library.InvalidName),
                         ("../x.3mf", library.InvalidName), ("a.3mf", library.InvalidName), (".hid.3mf", library.InvalidName)):
            with self.assertRaises(exc, msg=new):
                self.lib.rename("a.3mf", new)
        with self.assertRaises(library.NotFound):
            self.lib.rename("nope.3mf", "x.3mf")
        self.assertEqual([x["name"] for x in self.lib.entries()], ["a.3mf", "b.3mf"])

    def test_capitals_only_and_rollback_when_the_index_cannot_be_saved(self):
        self.lib.add_bytes("phone stand.3mf", make_3mf())
        self.assertEqual(self.lib.rename("phone stand.3mf", "Phone Stand.3mf")["name"], "Phone Stand.3mf")
        before = {x["name"]: x["thumb"] for x in self.lib.entries()}
        with mock.patch.object(self.lib, "_save", side_effect=OSError("disk full")):
            with self.assertRaises(OSError):
                self.lib.rename("Phone Stand.3mf", "Other.3mf")
        self.assertEqual({x["name"]: x["thumb"] for x in self.lib.entries()}, before)       # file, preview and index all back
        self.assertTrue(os.path.isfile(os.path.join(self.lib.files_dir, "Phone Stand.3mf")))
        self.assertFalse(os.path.exists(os.path.join(self.lib.files_dir, "Other.3mf")))

    def test_find_by_sha(self):
        e = self.lib.add_bytes("a.3mf", make_3mf())
        self.assertEqual(self.lib.find_by_sha(e["sha256"])["name"], "a.3mf")
        self.assertIsNone(self.lib.find_by_sha("0" * 64))


