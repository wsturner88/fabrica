def make_3mf(objects=3, model_id="C12", model_name="Bambu Lab P1S", secs=3900, tag="") -> bytes:
    objs = "".join(f'<object identify_id="{i}" name="Part {i}" skipped="false"/>' for i in range(objects))
    info = ('<?xml version="1.0" encoding="UTF-8"?><config><header><header_item key="X-BBL-Client-Type" value="slicer"/></header>'
            '<plate><metadata key="index" value="1"/>' + f'<metadata key="printer_model_id" value="{model_id}"/>'
            f'<metadata key="prediction" value="{secs}"/><metadata key="weight" value="12.5"/>' + objs +
            '<filament id="1" tray_info_idx="GFA00" type="PLA" color="#FF0000" used_m="1.0" used_g="3.0"/>'
            '<filament id="2" tray_info_idx="GFA00" type="PETG" color="#0A2989" used_m="1.0" used_g="9.5"/>'
            '</plate></config>')
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        z.writestr("Metadata/slice_info.config", info)
        z.writestr("Metadata/project_settings.config", json.dumps({"printer_model": model_name, "layer_height": "0.2"}))
        z.writestr("3D/3dmodel.model", '<?xml version="1.0"?><model><metadata name="Application">Slicer-1.0</metadata></model>')
        z.writestr("Metadata/plate_1.gcode", "; total layer number: 69\nG28\n")
        z.writestr("Metadata/plate_1.png", PNG)
        if tag:
            z.writestr("Metadata/tag.txt", tag)
    return buf.getvalue()


